// Writes THIRD_PARTY.md (NFR-LIC-4): every package that ships to players, its version and
// licence, plus the web fonts and generated media. Run `node scripts/third-party.mjs`
// after changing dependencies; `npm run check` fails if the file is out of date.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));

// Runtime dependencies and everything they pull in (devDependencies never reach players).
const seen = new Map();
const queue = Object.keys(pkg.dependencies ?? {});
while (queue.length) {
  const name = queue.shift();
  if (seen.has(name)) continue;
  const entry = lock.packages[`node_modules/${name}`];
  if (!entry) continue;
  let license = entry.license;
  const manifest = join(root, "node_modules", name, "package.json");
  if (!license && existsSync(manifest)) license = JSON.parse(readFileSync(manifest, "utf8")).license;
  seen.set(name, { version: entry.version, license: license ?? "UNKNOWN" });
  queue.push(...Object.keys(entry.dependencies ?? {}));
}

const rows = [...seen.entries()].sort(([a], [b]) => a.localeCompare(b));
const lines = [
  "# Third-party software and assets",
  "",
  "Generated by `node scripts/third-party.mjs`. Lists everything that ships to players: npm runtime packages, web fonts and generated media.",
  "",
  "## npm packages (runtime)",
  "",
  "| Package | Version | Licence |",
  "| --- | --- | --- |",
  ...rows.map(([name, { version, license }]) => `| ${name} | ${version} | ${license} |`),
  "",
  "## Fonts",
  "",
  "| Font | Source | Licence |",
  "| --- | --- | --- |",
  "| General Sans | Fontshare (Indian Type Foundry) | ITF Free Font License |",
  "| DM Sans | Google Fonts | SIL Open Font License 1.1 |",
  "| JetBrains Mono | Google Fonts | SIL Open Font License 1.1 |",
  "",
  "Fonts are loaded from the Fontshare and Google Fonts CDNs at run time.",
  "",
  "## Generated media",
  "",
  "| Asset | Made with | Terms |",
  "| --- | --- | --- |",
  "| Rules narration (`public/explainer/<lang>/*.mp3`) | ElevenLabs text to speech, voice Don | ElevenLabs plan terms; see NARRATION.md |",
  "| Intro sting and music (`public/explainer/sfx/`) | ElevenLabs sound effects and music | ElevenLabs plan terms |",
  "",
];
const out = lines.join("\n");
const target = join(root, "THIRD_PARTY.md");
if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== out) {
    console.error("THIRD_PARTY.md is out of date: run `node scripts/third-party.mjs`");
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
  console.log(`THIRD_PARTY.md: ${rows.length} runtime packages`);
}
